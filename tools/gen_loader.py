"""Xebec - turn M-VAVE's OTA loader into a C file for the image.

    tools/gen_loader.py vendor/m-vave/ota.bin OUT.c

Refuses the file unless it is exactly the one in vendor/m-vave/README.md:
the SHA-256, the file head's own CRC, the loader's CRC and length, and the
loader's inner head (load address 0x01C0A800).
"""
import hashlib
import struct
import sys

SHA256 = "ef1f2db89b011fa53e71df363f0122de0ea896618c53fb53e8da676322004541"
HEAD_CRC, BODY_CRC, BODY_LEN = 0xEBAA, 0x5881, 0x4DE1
LOAD_ADDR = 0x01C0A800


def crc16(data, c=0):
    """CRC-16, polynomial 0x1021, start 0 (JieLi's file heads)."""
    for b in data:
        c ^= b << 8
        for _ in range(8):
            c = ((c << 1) ^ 0x1021 if c & 0x8000 else c << 1) & 0xFFFF
    return c


def main():
    src, out = sys.argv[1], sys.argv[2]
    data = open(src, "rb").read()
    problems = []
    if hashlib.sha256(data).hexdigest() != SHA256:
        problems.append("SHA-256 differs")
    head, body = data[:32], data[32:]
    hcrc, dcrc, off, length = struct.unpack_from("<HHII", head, 0)
    if hcrc != HEAD_CRC or crc16(head[2:32]) != hcrc:
        problems.append("file head CRC")
    if off != 0x20 or length != BODY_LEN or len(body) != BODY_LEN or head[12] != 0x41:
        problems.append("file head layout")
    if dcrc != BODY_CRC or crc16(body) != dcrc:
        problems.append("loader CRC")
    inner = body[:32]
    if crc16(inner[2:32]) != struct.unpack_from("<H", inner, 0)[0] or \
            struct.unpack_from("<I", inner, 8)[0] != LOAD_ADDR:
        problems.append("loader's inner head")
    if problems:
        sys.exit(f"{src}: not M-VAVE's OTA loader as expected: {', '.join(problems)}")

    rows = ",\n".join("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16])
                      for i in range(0, len(data), 16))
    open(out, "w").write(f"""/* Generated by tools/gen_loader.py from vendor/m-vave/ota.bin: do not edit.
 *
 * M-VAVE's OTA loader (usb_hid_ota.bin), unchanged.
 * Copyright (C) 2026 M-VAVE. Licensed under the Apache License, Version 2.0:
 * vendor/m-vave/LICENSE-Apache-2.0.txt. Stored and started by Xebec, not linked.
 * SHA-256 {SHA256}
 */
#include "ota_stage.h"

const uint32_t xb_ota_loader_len = {len(data)}u;
const uint8_t xb_ota_loader[{len(data)}] = {{
{rows}
}};
""")
    print(f"{out}: M-VAVE OTA loader, {len(data)} bytes, checked")


if __name__ == "__main__":
    main()
